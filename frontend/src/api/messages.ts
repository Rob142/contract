export function messageOf(error: unknown): string {
  if (error instanceof ApiError) {
    return MESSAGES[error.code] ?? (error.status >= 500 ? '서버 오류가 발생했어요. 잠시 후 다시 시도해 주세요.' : '요청을 처리하지 못했어요.')
  }
  return '알 수 없는 오류가 발생했어요.'
}
